/**
 * Repair the Android adaptive-icon layers after `capacitor-assets generate`.
 *
 * Run this every time the icons are regenerated — `npm run generate:assets`
 * chains the two so it cannot be forgotten. @capacitor/assets (3.0.5) gets two
 * things wrong for adaptive icons:
 *
 *  1. Size. Its own templates define the adaptive layers on the 108dp canvas
 *     (mdpi 108 ... xxxhdpi 432), but the files it writes come out at the 48dp
 *     *legacy* sizes (mdpi 48 ... xxxhdpi 192). Android then upscales them
 *     ~2.25x and the launcher icon looks soft on every modern device.
 *
 *  2. Masking. It wraps `<background>` in `<inset android:inset="16.7%">`. An
 *     InsetDrawable shrinks inward, so the black field stops short of the icon
 *     edge and the launcher's own backdrop shows through around it. An adaptive
 *     background has to bleed to all four edges. Only the foreground is
 *     constrained, by the 108dp -> 66dp safe zone, and that padding belongs
 *     inside the artwork — which is how Android Studio's own template does it.
 *
 * The legacy `ic_launcher.png` / `ic_launcher_round.png` that the tool emits are
 * correct, so they are left alone.
 *
 * `sharp` is resolved from @capacitor/assets, which bundles it; this script is
 * only ever run next to that tool.
 */
import { createRequire } from 'node:module';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const sharp = require('sharp');

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RES = path.join(ROOT, 'android/app/src/main/res');
const SOURCE = path.join(ROOT, 'assets/icon-foreground.png');

/** The 108dp adaptive canvas, per density bucket. */
const DENSITIES = { ldpi: 81, mdpi: 108, hdpi: 162, xhdpi: 216, xxhdpi: 324, xxxhdpi: 432 };

/**
 * Fraction of the 108dp canvas the mark occupies. The guaranteed-visible safe
 * zone is 66/108 = 61%, and launchers crop to the central 72dp before masking,
 * so 52% fills the visible viewport generously while clearing every OEM shape.
 */
const ART_FRACTION = 0.52;

const TRANSPARENT = { r: 0, g: 0, b: 0, alpha: 0 };
const BLACK = { r: 0, g: 0, b: 0, alpha: 1 };

const XML = `<?xml version="1.0" encoding="utf-8"?>
<!--
    Generated by scripts/fix-adaptive-icons.mjs. Do not hand-edit: running
    \`npm run generate:assets\` rewrites this file.

    No <inset> on either layer, deliberately. The background must bleed to all
    four edges, because an adaptive icon is masked to whatever shape the
    launcher uses and an inset background leaves the launcher's backdrop showing
    in the corners. The foreground needs no inset either — the PNG already
    carries the safe-zone padding as transparent margin, so insetting would
    shrink the mark twice.

    <monochrome> drives Android 13+ themed icons, which tint the layer's alpha
    to the user's wallpaper palette. The mark is a flat silhouette, so the
    foreground doubles as the monochrome source.
-->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`;

if (!existsSync(SOURCE)) {
  console.error(`fix-adaptive-icons: missing ${path.relative(ROOT, SOURCE)}`);
  process.exit(1);
}

// The source already has transparent margin baked in; trim to the ink so the
// fraction below is measured against the mark itself, not its padding.
const ink = await sharp(SOURCE).trim().png().toBuffer();

for (const [density, size] of Object.entries(DENSITIES)) {
  const dir = path.join(RES, `mipmap-${density}`);
  if (!existsSync(dir)) continue;

  await sharp({ create: { width: size, height: size, channels: 4, background: BLACK } })
    .png()
    .toFile(path.join(dir, 'ic_launcher_background.png'));

  const art = Math.round(size * ART_FRACTION);
  const scaled = await sharp(ink)
    .resize(art, art, { fit: 'inside', kernel: 'lanczos3' })
    .toBuffer();

  await sharp({ create: { width: size, height: size, channels: 4, background: TRANSPARENT } })
    .composite([{ input: scaled, gravity: 'center' }])
    .png()
    .toFile(path.join(dir, 'ic_launcher_foreground.png'));

  console.log(`  mipmap-${density}: ${size}x${size} (mark ${art}px)`);
}

for (const file of ['ic_launcher.xml', 'ic_launcher_round.xml']) {
  writeFileSync(path.join(RES, 'mipmap-anydpi-v26', file), XML);
  console.log(`  mipmap-anydpi-v26/${file}`);
}
